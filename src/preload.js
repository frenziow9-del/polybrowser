const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('browser', {
  ready: () => ipcRenderer.invoke('browser:ready'),
  createTab: (url) => ipcRenderer.invoke('tabs:create', url),
  closeTab: (id) => ipcRenderer.invoke('tabs:close', id),
  activateTab: (id) => ipcRenderer.invoke('tabs:activate', id),
  reopenClosed: () => ipcRenderer.invoke('tabs:reopen'),
  navAction: (action) => ipcRenderer.invoke('nav:action', action),
  go: (input) => ipcRenderer.invoke('nav:go', input),
  find: (text, options) => ipcRenderer.invoke('page:find', text, options),
  findStop: () => ipcRenderer.invoke('page:findStop'),
  toggleBookmark: () => ipcRenderer.invoke('bookmark:toggle'),
  openMenu: (x, y) => ipcRenderer.invoke('menu:open', x, y),
  newWindow: (incognito) => ipcRenderer.invoke('window:new', incognito),
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  getBookmarks: () => ipcRenderer.invoke('bookmarks:get'),
  removeBookmark: (id) => ipcRenderer.invoke('bookmarks:remove', id),
  setChromeHeight: (h) => ipcRenderer.send('ui:chrome-height', h),
  onState: (cb) => ipcRenderer.on('state', (_e, s) => cb(s)),
  onSettings: (cb) => ipcRenderer.on('settings', (_e, s) => cb(s)),
  onBookmarks: (cb) => ipcRenderer.on('bookmarks-changed', (_e, b) => cb(b)),
  onDownloads: (cb) => ipcRenderer.on('downloads-changed', (_e, d) => cb(d)),
  onFocusUrl: (cb) => ipcRenderer.on('focus-url', () => cb()),
  onFindOpen: (cb) => ipcRenderer.on('find-open', () => cb()),
  onFindClose: (cb) => ipcRenderer.on('find-close', () => cb()),
  onFindResult: (cb) => ipcRenderer.on('find-result', (_e, r) => cb(r)),
  onTabSearch: (cb) => ipcRenderer.on('tab-search-open', () => cb()),
  onToggleBookmarksBar: (cb) => ipcRenderer.on('toggle-bookmarks-bar', () => cb()),
});
